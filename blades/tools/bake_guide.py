#!/usr/bin/env python3
"""Bake Guide components from the selected 2008 video, preserving RGB exactly."""
from pathlib import Path
import json
from reference_io import decode,write_png
ROOT=Path(__file__).resolve().parents[1]
REF=ROOT.parent/'References/widescreen/guide'

def encode(rows):
 out=bytearray();prev=(0,0,0);run=0
 for row in rows:
  for x in range(0,len(row),3):
   c=tuple(row[x:x+3])
   if c==prev:
    run+=1
    if run==128:out.append(255);run=0
    continue
   if run:out.append(128+run-1);run=0
   ds=[c[k]-prev[k] for k in range(3)]
   if all(-2<=v<=1 for v in ds):out.append((ds[0]+2)*16+(ds[1]+2)*4+ds[2]+2)
   else:out.extend((64,*c))
   prev=c
 if run:out.append(128+run-1)
 return out

def crop(rows,x,y,w,h):return [bytearray(r[x*3:(x+w)*3]) for r in rows[y:y+h]]
_,_,main=decode(REF/'main.png');_,_,empty=decode(REF/'empty.png');_,_,right=decode(REF/'exit.png')
W=570;RW=586
# Trace the last silver-rail pixel; do not copy any of the captured background.
edges=[]
for y in range(720):
 xs=[x for x in range(480,W) if max(empty[y][x*3:x*3+3])-min(empty[y][x*3:x*3+3])<48 and min(empty[y][x*3:x*3+3])>100]
 edges.append(max(xs)+1 if xs else 530)
left_empty=crop(empty,0,0,W,720)
left_main=crop(main,0,0,W,720)
# Clock/controller status are live. Avoid showing the recorded time/battery level.
for rows in [left_empty,left_main]:
 for y in range(50,89):
  c=empty[y][330*3:330*3+3]
  for x in range(100,483):rows[y][x*3:x*3+3]=c
# Replace the reference player's profile count with native status text.
for y in range(118,183):
 u=(y-115)/(185-115)
 for x in range(182,470):
  a=main[115][x*3:x*3+3];b=main[185][x*3:x*3+3]
  left_main[y][x*3:x*3+3]=bytes(round(a[k]+(b[k]-a[k])*u) for k in range(3))
# The right confirmation is a separate, oppositely curved Guide surface.
right_empty=crop(right,1280-RW,0,RW,720)
right_edges=[]
for y in range(720):
 xs=[x for x in range(0,100) if min(right_empty[y][x*3:x*3+3])>100 and max(right_empty[y][x*3:x*3+3])-min(right_empty[y][x*3:x*3+3])<48]
 right_edges.append(min(xs) if xs else 50)
for y in range(103,558):
 c=right_empty[y][(RW-20)*3:(RW-19)*3]
 for x in range(94,RW-12):right_empty[y][x*3:x*3+3]=c
# Remove the captured warning title; each panel title is live.
for y in range(52,89):
 c=right_empty[y][500*3:501*3]
 for x in range(90,RW-10):right_empty[y][x*3:x*3+3]=c
_,_,error=decode(REF/'profile-required.png')
assets=[('main',left_main),('empty',left_empty),('right',right_empty),('warning',crop(right,790,58,28,28)),('error',crop(error,790,58,28,28))]
parts=['#include "guide_art.h"','/* Generated by tools/bake_guide.py. Source times are in References/widescreen/guide/source.json. */']
for name,rows in assets:
 blob=encode(rows);parts.append(f'static const unsigned char art_{name}[] = {{')
 for i in range(0,len(blob),32):parts.append(','.join(map(str,blob[i:i+32]))+',')
 parts.append('};')
parts.append('const ReferenceAsset guide_art[5] = {')
for name,rows in assets:parts.append(f'{{{len(rows[0])//3},{len(rows)},sizeof art_{name},art_{name}}},')
parts.append('};')
parts.append('const unsigned short guide_left_edge[720] = {'+','.join(map(str,edges))+'};')
parts.append('const unsigned short guide_right_edge[720] = {'+','.join(map(str,right_edges))+'};')
(ROOT/'src/guide_art_data.c').write_text('\n'.join(parts)+'\n')
(ROOT/'src/guide_art.h').write_text('''#ifndef BLADES_GUIDE_ART_H
#define BLADES_GUIDE_ART_H
#include "reference_assets.h"
enum { GUIDE_ART_MAIN, GUIDE_ART_EMPTY, GUIDE_ART_RIGHT, GUIDE_ART_WARNING, GUIDE_ART_ERROR, GUIDE_ART_COUNT };
extern const ReferenceAsset guide_art[GUIDE_ART_COUNT];
extern const unsigned short guide_left_edge[720], guide_right_edge[720];
#endif
''')
(REF/'source.json').write_text(json.dumps({'url':'https://www.youtube.com/watch?v=5JPMeN1SkUE','source_fps':60,'scale':'1920x1080 -> 1280x720, Lanczos','frames_seconds':{'main':528.0,'empty':162.0,'signin':164.0,'exit':530.0,'profile-required':153.0},'components':'Traced panel silhouettes, original shell/control artwork. Captured profile count, clock, and battery state are removed and replaced with live/explicitly offline state.','timing_status':'Opening/closing easing is provisional pending frame-by-frame measurement.'},indent=2)+'\n')
print('Baked three Guide surfaces and per-row rail silhouettes.')
